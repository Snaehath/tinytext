"""Ground Truth Specification and Manifest for Independent Holdout 88.

Establishes independent, audited ground truth for every one of the 88 prompts in
data/instructions/v1_5_tool_use/independent_holdout_88.jsonl.

Separately defines for every prompt:
1. Expected route (CALC, FACT, EXTRACT, ANSWER, ABSTAIN) and acceptable routes
2. Expected outcome (correct_calculation, correct_fact, grounded_extraction, safe_absence,
   safe_abstention, correct_classification, correct_list, qualitative_explanation)
3. Scoring status (objectively_scored vs unscored) and justification
4. Tool requirement (True if a deterministic tool is genuinely required, False otherwise)
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import Enum
from typing import Any, Dict, List, Optional


class ToolPolicy(str, Enum):
    REQUIRED = "required"
    OPTIONAL = "optional"
    FORBIDDEN = "forbidden"



@dataclass(frozen=True)
class GroundTruthSpecification:
    prompt_id: str
    prompt: str
    category: str
    tool_policy: ToolPolicy
    expected_route: str
    acceptable_routes: List[str]
    expected_outcome: str
    scoring_status: str
    scoring_reason: str
    expected_target: Any
    source_passage: Optional[str] = None
    permitted_labels: Optional[List[str]] = None
    target_count: Optional[int] = None
    list_domain: Optional[str] = None

    @property
    def tool_required(self) -> bool:
        """Backward-compatibility property."""
        return self.tool_policy == ToolPolicy.REQUIRED


