def get_ground_truth(prompt_id: str) -> GroundTruthSpecification:
    if prompt_id not in HOLDOUT_88_MANIFEST:
        raise KeyError(f"Prompt ID '{prompt_id}' not found in 88-prompt holdout manifest.")
    return HOLDOUT_88_MANIFEST[prompt_id]


def audit_manifest_counts() -> Dict[str, Any]:
    """Reconciles manifest counts and verifies all categories match exact totals."""
    total = len(HOLDOUT_88_MANIFEST)
    tool_req = sum(1 for s in HOLDOUT_88_MANIFEST.values() if s.tool_required)
    no_tool = total - tool_req
    scored = sum(1 for s in HOLDOUT_88_MANIFEST.values() if s.scoring_status == "objectively_scored")
    unscored = total - scored

    by_outcome: Dict[str, int] = {}
    for s in HOLDOUT_88_MANIFEST.values():
        by_outcome[s.expected_outcome] = by_outcome.get(s.expected_outcome, 0) + 1

    by_route: Dict[str, int] = {}
    for s in HOLDOUT_88_MANIFEST.values():
        by_route[s.expected_route] = by_route.get(s.expected_route, 0) + 1

    return {
        "total_prompts": total,
        "tool_required_count": tool_req,
        "no_tool_required_count": no_tool,
        "objectively_scored_count": scored,
        "unscored_count": unscored,
        "by_outcome": by_outcome,
        "by_expected_route": by_route,
    }


def validate_manifest_consistency(manifest: Optional[Dict[str, GroundTruthSpecification]] = None) -> Dict[str, Any]:
    """Validates that every specification has an internally consistent, defensible policy."""
    errors: List[str] = []
    policy_counts = {p: 0 for p in ToolPolicy}
    target_manifest = manifest if manifest is not None else HOLDOUT_88_MANIFEST

    for pid, spec in target_manifest.items():
        policy_counts[spec.tool_policy] += 1

        if spec.tool_policy == ToolPolicy.REQUIRED:
            if spec.expected_route not in ("CALC", "FACT", "EXTRACT"):
                errors.append(f"{pid}: Tool required but expected_route is {spec.expected_route}")
            if "ANSWER" in spec.acceptable_routes:
                errors.append(f"{pid}: Tool required but ANSWER is in acceptable_routes")
            if not spec.tool_required:
                errors.append(f"{pid}: ToolPolicy.REQUIRED but tool_required property is False")
        elif spec.tool_policy == ToolPolicy.FORBIDDEN:
            if spec.expected_route in ("CALC", "FACT", "EXTRACT"):
                errors.append(f"{pid}: Tool forbidden but expected_route is {spec.expected_route}")
            if any(r in ("CALC", "FACT", "EXTRACT") for r in spec.acceptable_routes):
                errors.append(f"{pid}: Tool forbidden but tool route found in acceptable_routes: {spec.acceptable_routes}")
            if spec.tool_required:
                errors.append(f"{pid}: ToolPolicy.FORBIDDEN but tool_required property is True")
        elif spec.tool_policy == ToolPolicy.OPTIONAL:
            if "ANSWER" not in spec.acceptable_routes:
                errors.append(f"{pid}: Tool optional but ANSWER missing from acceptable_routes")
            if not any(r in ("CALC", "FACT", "EXTRACT") for r in spec.acceptable_routes):
                errors.append(f"{pid}: Tool optional but no tool route in acceptable_routes")
            if spec.tool_required:
                errors.append(f"{pid}: ToolPolicy.OPTIONAL but tool_required property is True")

    if errors:
        raise ValueError(f"Manifest policy validation failed with {len(errors)} errors:\n" + "\n".join(errors))

